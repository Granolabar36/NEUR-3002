# %matplotlib inline

import numpy as np
import matplotlib.pyplot as plt

# --- Neuron Parameters (realistic, in mV and pA) ---
C = 200.0       #capacitance
V_th = -55.0    #voltage threshold
V_reset = -65.0 #voltage when the membrane is hyperpolarized right after action potential
V_rest = -70.0  #voltage of membrane at rest
I_ext = 100   #external input current
dt = 0.1        #delta time = change in time

C2 = 200.0       #capacitance
V_th2 = -55.0    #voltage threshold
V_reset2 = -65.0 #voltage when the membrane is hyperpolarized right after action potential
V_rest2 = -70.0  #voltage of membrane at rest
I_ext2 = 150   #external input current
dt2 = 0.1


T = 100          # total simulation time in ms
dt = 0.1         # time step in ms
time = np.arange(0, T, dt)  # time vector

# --- Initialize voltage and spike times ---
V = np.full_like(time, V_rest)  # set all values to resting voltage
spike_times = []

V2 = np.full_like(time, V_rest2)  # set all values to resting voltage
spike_times2 = []

# --- Simulation---
for i in range(1, len(time)):
    dV = (I_ext / C) * dt       # ΔV = (I / C) * dt, in mV
    V[i] = V[i-1] + dV

    if V[i] >= V_th:
        V[i-1] = 40.0           # mark spike as +40 mV (for visualization)
        V[i] = V_reset
        spike_times.append(time[i])

for i in range(1, len(time)):
    dV2 = (I_ext2 / C2) * dt       # ΔV = (I / C) * dt, in mV
    V2[i] = V2[i-1] + dV2

    if V2[i] >= V_th2:
        V2[i-1] = 40.0           # mark spike as +40 mV (for visualization)
        V2[i] = V_reset2
        spike_times2.append(time[i])

# --- Plotting ---
plt.figure(figsize=(10, 4))
plt.plot(time, V, label='Neuron Voltage')
plt.axhline(V_th, color='r', linestyle='--', label='V Threshold')
plt.plot(time, V2, label='Neuron Voltage 2')

plt.xlabel('Time') #what should the x be?
plt.ylabel('Voltage') #what should the y be?
plt.title('Voltage vs Time') #what is a good title?
plt.grid(True)
plt.show()

